function fluid = chocolate()
% CHOCOLATE Define a Newtonian approximation for molten compound chocolate.
%   Viscosity is approximately 0.50 Pa s at 60 degrees Celsius, read from
%   Toker et al. (2017), Figure 5, for the 40 rpm, 10 minute formulation
%   at 50 s^-1. Constant viscosity at lower shear rates is an assumption.
%   Density and liquid surface tension are separate
%   representative values; the complete property set is not one measured
%   sample. Yield stress, shear thinning, and crystallization are excluded.

    reference = "Toker et al. (2017), Figure 5, doi:10.1111/ijfs.13336; " ...
        + "compound chocolate refined at 40 rpm for 10 minutes. " ...
        + "Viscosity approximately 0.50 Pa s at 60 degrees Celsius, " ...
        + "read from the temperature sweep at 50 s^-1. " ...
        + "Table 3 reports a Newtonian fit over 0.1 to 100 s^-1 at 40 degrees Celsius; " ...
        + "constant viscosity at lower shear rates and at 60 degrees Celsius is assumed. " ...
        + "Representative density: Townsend and Wilson (2016), Table 1, " ...
        + "https://doi.org/10.1088/0143-0807/37/1/015803. " ...
        + "Representative liquid surface tension 0.030 N/m: Keijbets (2009), " ...
        + "PhD thesis, Figure 4.1, measurements at 50 degrees Celsius, " ...
        + "https://etheses.whiterose.ac.uk/id/eprint/12740/. " ...
        + "Density and surface tension have no temperature correction. " ...
        + "Properties are not measurements of one common sample at 60 degrees Celsius. " ...
        + "Yield stress, shear thinning, and crystallization are excluded.";
    fluid = app.internal.materials.Fluid("Molten compound chocolate (Newtonian approximation)", ...
        60, 1270, 0.50, 0.030, reference);
end
