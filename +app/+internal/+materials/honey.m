function fluid = honey()
% HONEY Define a Newtonian approximation for acacia honey at 30 degrees Celsius.
%   Viscosity is reported by Nayik et al. (2018), Table 2. Density and
%   surface tension are representative values from separate honey samples.
%   The combined property set is not a measurement of one common sample.
%   Crystallization and non-Newtonian effects are excluded.

    reference = "Newtonian approximation for acacia honey at 30 degrees Celsius. " ...
        + "Viscosity 0.27 Pa s: Nayik et al. (2018), Table 2, doi:10.1016/j.jssas.2016.07.003. " ...
        + "Representative density 1420 kg/m^3: Meli Acacia Honey technical sheet (2022), " ...
        + "reported density range 1398 to 1445 kg/m^3 across moisture and temperature conditions. " ...
        + "Representative surface tension 0.0801 N/m: Tyowua et al. (2023), Table 1, " ...
        + "doi:10.3389/frsfm.2023.1163393; a separate honey sample at 30 +/- 2 degrees Celsius. " ...
        + "The combined properties are an approximation assembled from separate sources. " ...
        + "Crystallization and non-Newtonian effects are excluded.";
    fluid = app.internal.materials.Fluid("Honey (Newtonian approximation)", 30, 1420, 0.27, 0.0801, reference);
end
